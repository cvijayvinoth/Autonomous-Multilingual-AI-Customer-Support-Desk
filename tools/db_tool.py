"""Database Logging Tool for AutoGen Log Agent supporting Message Threads."""

from datetime import datetime
import random
from database.db_service import SessionLocal
from database.models import Ticket, TicketMessage


def log_ticket_to_db(
    customer_name: str,
    complaint: str,
    category: str,
    urgency: str,
    sentiment: str,
    kb_sources: str,
    response: str,
    status: str,
    escalation_reason: str,
    customer_email: str = "",
    detected_language: str = "English",
    existing_ticket_id: str = "",
) -> str:
    """Logs the final ticket details or appends a reply to an existing thread.

    Args:
        customer_name: Name or ID of the customer.
        complaint: The customer's latest message or inquiry.
        category: Classified category (Shipping, Refund, Billing, Account, Product, Other).
        urgency: Urgency level (Low, Medium, High).
        sentiment: Customer sentiment (Positive, Neutral, Frustrated, Angry).
        kb_sources: Markdown files used as source, or 'None'.
        response: Final customer-facing reply generated by the team.
        status: Ticket status ('Resolved' or 'Escalated').
        escalation_reason: Reason if escalated, or 'None'.
        customer_email: Email address of customer.
        detected_language: Customer input language.
        existing_ticket_id: Existing ticket ID to append to (optional).

    Returns:
        Status message with Ticket ID.
    """
    clean_email = customer_email.strip() if customer_email and customer_email.lower() not in ["none", "null", ""] else ""
    target_id = existing_ticket_id.strip() if existing_ticket_id and existing_ticket_id.lower() not in ["none", "null", ""] else ""

    db = SessionLocal()
    try:
        ticket = None
        if target_id:
            ticket = db.query(Ticket).filter(Ticket.ticket_id == target_id).first()

        if not ticket:
            # Create a new ticket
            t_id = f"TKT-{random.randint(1000, 9999)}"
            ticket = Ticket(
                ticket_id=t_id,
                created_at=datetime.utcnow(),
                updated_at=datetime.utcnow(),
                customer_name=customer_name or "Anonymous",
                customer_email=clean_email,
                detected_language=detected_language or "English",
                category=category,
                urgency=urgency,
                sentiment=sentiment,
                status=status,
                escalation_reason=escalation_reason or "None",
            )
            db.add(ticket)
            db.commit()

            # Record customer query and AI response as the initial thread entries
            db.add(TicketMessage(ticket_id=t_id, sender="Customer", message_text=complaint))
            db.add(TicketMessage(ticket_id=t_id, sender="AI_Assistant", message_text=response))
            db.commit()
            return f"SUCCESS: New Ticket {t_id} created for {clean_email or 'Anonymous'}."

        else:
            # Append follow-up into existing ticket thread
            ticket.urgency = urgency
            ticket.sentiment = sentiment
            ticket.status = status
            ticket.updated_at = datetime.utcnow()
            if status == "Escalated":
                ticket.escalation_reason = escalation_reason
            if clean_email and not ticket.customer_email:
                ticket.customer_email = clean_email

            db.add(TicketMessage(ticket_id=ticket.ticket_id, sender="Customer", message_text=complaint))
            db.add(TicketMessage(ticket_id=ticket.ticket_id, sender="AI_Assistant", message_text=response))
            db.commit()
            return f"SUCCESS: Follow-up reply saved under existing Ticket {ticket.ticket_id}."

    except Exception as e:
        db.rollback()
        return f"ERROR: Failed to persist ticket message: {str(e)}"
    finally:
        db.close()